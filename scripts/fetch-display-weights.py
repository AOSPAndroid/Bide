"""Build-time only: the extra weights of display families that ads, cards and
flyers use (Raleway Light, Nunito ExtraBold, Montserrat Black...), cut from the
same pinned Google Fonts revision as the extended library (fetch-font-library.py)
and subset the same way. Each weight is a family of its own ("Raleway Light"),
like src/font-weights.ts. Internal names are "bide <family> <weight>", as the
library's own derivatives, so no reserved font name is used inside a modified
font. Requires fonttools; the shipped application never runs this script.
Writes src/browser/fonts/weights/*.ttf and src/font-display-weights.ts.
"""
from pathlib import Path
import json,re,urllib.request,urllib.parse,io,hashlib
from fontTools.ttLib import TTFont
from fontTools import subset
from fontTools.varLib.instancer import instantiateVariableFont

ROOT=Path(__file__).resolve().parent.parent
revision=json.loads((ROOT/'scripts/font-library-manifest.json').read_text())['revision']
base=f'https://raw.githubusercontent.com/google/fonts/{revision}/ofl/'
folder=ROOT/'src/browser/fonts/weights'
WEIGHTS={
 'Raleway':[('ExtraLight',200),('Light',300),('Medium',500),('SemiBold',600),('ExtraBold',800),('Black',900)],
 'Nunito':[('Light',300),('SemiBold',600),('ExtraBold',800),('Black',900)],
 'Montserrat':[('ExtraBold',800),('Black',900)],
 'Poppins':[('ExtraBold',800),('Black',900)],
 'Open Sans':[('ExtraBold',800)],
 'Inter':[('ExtraBold',800),('Black',900)],
 'Roboto':[('Black',900)],
}
UNICODES=list(range(0x250))+list(range(0x1e00,0x1f00))+list(range(0x2000,0x2070))+list(range(0x20a0,0x20d0))+list(range(0x2100,0x2300))

def get(url):
 with urllib.request.urlopen(url,timeout=120) as r:return r.read()

def build(family,name,weight,cache):
 slug=re.sub('[^a-z0-9]','',family.lower());url=base+slug+'/'
 if slug not in cache:
  metadata=get(url+'METADATA.pb').decode();blocks=re.findall(r'fonts \{(.*?)\n\}',metadata,re.S)
  cache[slug]=[(re.search(r'filename: "([^"]+)"',b).group(1),re.search(r'style: "([^"]+)"',b).group(1),int(re.search(r'weight: (\d+)',b).group(1))) for b in blocks]
 records=[r for r in cache[slug] if r[1]=='normal' and (r[2]==weight or '[' in r[0])]
 filename=min(records,key=lambda r:(r[2]!=weight and '[' not in r[0],abs(r[2]-weight)))[0]
 key=slug+'/'+filename
 if key not in cache:cache[key]=get(url+urllib.parse.quote(filename))
 font=TTFont(io.BytesIO(cache[key]))
 if 'fvar' in font:
  axes={a.axisTag:(weight if a.axisTag=='wght' else a.defaultValue) for a in font['fvar'].axes}
  font=instantiateVariableFont(font,axes,inplace=True)
 options=subset.Options();options.name_IDs=['*'];options.name_legacy=True;options.name_languages=['*']
 subsetter=subset.Subsetter(options=options);subsetter.populate(unicodes=UNICODES);subsetter.subset(font)
 internal=f'bide {family} {name}'
 for ident,value in [(1,internal),(2,'Regular'),(3,internal),(4,internal),(6,f'bide-{slug}-{name}'),(16,internal),(17,'Regular')]:
  for record in list(font['name'].names):
   if record.nameID==ident:font['name'].names.remove(record)
  font['name'].setName(value,ident,3,1,0x409)
 font['OS/2'].usWeightClass=400
 target=folder/(family.replace(' ','')+'-'+name+'.ttf');font.save(target);font.close()
 return {'family':f'{family} {name}','file':target.name,'source':url+urllib.parse.quote(filename),'weight':weight,'sha256':hashlib.sha256(target.read_bytes()).hexdigest()}

cache={};faces=[build(family,name,weight,cache) for family,items in WEIGHTS.items() for name,weight in items]
(ROOT/'scripts/display-weights-manifest.json').write_text(json.dumps({'revision':revision,'faces':faces},indent=2)+'\n')
imports=[f"import d{i} from './browser/fonts/weights/{f['file']}';" for i,f in enumerate(faces)]
entries=[f"{{family:{json.dumps(f['family'])},category:'sans',faces:[{{style:'Regular',url:d{i}}}]}}" for i,f in enumerate(faces)]
(ROOT/'src/font-display-weights.ts').write_text('// Generated by scripts/fetch-display-weights.py: weights of display families\n// (Raleway Light, Nunito ExtraBold...) for text set over ads, cards and flyers.\n'+'\n'.join(imports)+'\nexport const displayWeightFonts=[\n'+',\n'.join(entries)+'\n];\n')
for f in faces:print(f['family'],f['file'],(folder/f['file']).stat().st_size)
